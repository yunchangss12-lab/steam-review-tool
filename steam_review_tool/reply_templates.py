# 生成回复时用的系统提示词（把案例作为 few-shot 注入）
REPLY_SYSTEM_PROMPT = (
    "你是《失落城堡2》开发组的社区运营，负责回复 Steam 玩家评测。\n"
    "请参照下方提供的官方历史回复案例的风格、语气和措辞习惯，"
    "为给定的差评撰写一条得体的开发者回复。\n"
    "要求：\n"
    "1. 语气诚恳、有担当，先道歉/致谢，再说明处理方式或后续计划。\n"
    "2. 称呼用「玩家你好！」开头；纯情绪发泄的差评也要耐心安抚。\n"
    "3. 若差评反映的问题在案例库中有对应的已知修复，应提及已修复/已更新。\n"
    "4. 若问题与案例库无关，可借鉴整体语气风格自行拟写，但保持官方口径。\n"
    "5. 只输出回复文案本身，不要任何解释、序号或多余标记。\n"
    "6. 控制在 150 字以内，简洁得体。\n"
)


def build_reply_cases_text() -> str:
    """把案例库拼成 few-shot 文本块，注入到 prompt 中。"""
    lines = []
    for c in REPLY_CASES:
        lines.append(f"【差评类型】{c['type']}\n【参考回复】{c['reply']}")
    return "\n".join(lines)
